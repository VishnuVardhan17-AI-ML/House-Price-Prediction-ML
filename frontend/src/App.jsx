import { useState } from "react";
import {
  Home,
  IndianRupee,
  Ruler,
  BedDouble,
  MapPin,
  Sparkles,
  TrendingUp,
  LoaderCircle,
  AlertCircle,
  CheckCircle2,
} from "lucide-react";
import "./App.css";

const API_URL = "http://127.0.0.1:8000";

function App() {
  const [form, setForm] = useState({
    area: 1400,
    bedrooms: 3,
    location: "Whitefield",
    resale: 1,
  });

  const [predictedPrice, setPredictedPrice] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [note, setNote] = useState("");

  const updateField = (event) => {
    const { name, value } = event.target;

    setForm((previous) => ({
      ...previous,
      [name]:
        name === "location" ? value : Number(value),
    }));

    setPredictedPrice(null);
    setError("");
    setNote("");
  };

  const money = (value) =>
    new Intl.NumberFormat("en-IN", {
      style: "currency",
      currency: "INR",
      maximumFractionDigits: 0,
    }).format(value);

  const handlePredict = async (event) => {
    event.preventDefault();
    setLoading(true);
    setError("");
    setPredictedPrice(null);
    setNote("");

    try {
      const response = await fetch(`${API_URL}/predict`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          area: Number(form.area),
          bedrooms: Number(form.bedrooms),
          location: form.location.trim(),
          resale: Number(form.resale),
          amenities: {},
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(
          typeof data.detail === "string"
            ? data.detail
            : JSON.stringify(data.detail || "Prediction failed.")
        );
      }

      if (typeof data.predicted_price !== "number") {
        throw new Error("Invalid prediction received from backend.");
      }

      setPredictedPrice(data.predicted_price);
      setNote(data.note || "Estimate generated by the trained ML model.");
    } catch (err) {
      setError(
        err instanceof TypeError
          ? "Backend connection failed. Check that FastAPI is running on port 8000."
          : err.message
      );
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="app-shell">
      <aside className="sidebar">
        <div className="brand">
          <div className="brand-icon"><Home size={23} /></div>
          <div>
            <h2>EstateIQ</h2>
            <span>AI PROPERTY INSIGHTS</span>
          </div>
        </div>

        <div className="nav-label">WORKSPACE</div>
        <div className="nav-item active">
          <TrendingUp size={19} /> Price Prediction
        </div>
        <div className="nav-item">
          <Home size={19} /> Property Analysis
        </div>

        <div className="sidebar-bottom">
          <div className="avatar">VV</div>
          <div>
            <strong>Vishnu Vardhan</strong>
            <span>ML Project</span>
          </div>
        </div>
      </aside>

      <main className="main-content">
        <header className="topbar">
          <div>
            <span className="eyebrow">MACHINE LEARNING / REGRESSION</span>
            <h1>House Price Prediction</h1>
            <p>Estimate a property's value using your trained machine learning model.</p>
          </div>
          <div className="status-pill"><span /> ML API integration</div>
        </header>

        <section className="welcome-banner">
          <div>
            <span className="banner-label">
              <Sparkles size={15} /> AI-POWERED PROPERTY ESTIMATION
            </span>
            <h2>Find your property's estimated value.</h2>
            <p>Enter the property details below to generate a prediction.</p>
          </div>
          <div className="banner-house">
            <Home size={72} strokeWidth={1.1} />
          </div>
        </section>

        <div className="content-grid">
          <section className="panel form-panel">
            <div className="panel-heading">
              <div className="heading-icon"><Home size={20} /></div>
              <div>
                <h3>Property details</h3>
                <p>Enter the details of your property</p>
              </div>
            </div>

            <form onSubmit={handlePredict}>
              <label className="field-label">
                <Ruler size={16} /> Built-up area (sq. ft.)
              </label>
              <input
                name="area"
                type="number"
                min="1"
                value={form.area}
                onChange={updateField}
                required
              />

              <label className="field-label">
                <BedDouble size={16} /> Bedrooms
              </label>
              <input
                name="bedrooms"
                type="number"
                min="1"
                max="20"
                value={form.bedrooms}
                onChange={updateField}
                required
              />

              <label className="field-label">
                <MapPin size={16} /> Location
              </label>
              <input
                name="location"
                type="text"
                value={form.location}
                onChange={updateField}
                placeholder="e.g. Whitefield"
                required
              />

              <label className="field-label">
                <Home size={16} /> Property type
              </label>
              <select
                name="resale"
                value={form.resale}
                onChange={updateField}
              >
                <option value={1}>Resale property</option>
                <option value={0}>New property</option>
              </select>

              <button
                className="predict-button"
                type="submit"
                disabled={loading}
              >
                {loading ? (
                  <>
                    <LoaderCircle className="spin" size={18} />
                    Predicting...
                  </>
                ) : (
                  <>
                    <Sparkles size={18} />
                    Predict house price
                  </>
                )}
              </button>
            </form>

            <p className="demo-note">
              Powered by your trained Scikit-learn model.
            </p>
          </section>

          <section className="right-column">
            <div className="panel result-panel">
              <span className="result-label">
                <IndianRupee size={16} /> PREDICTED PROPERTY VALUE
              </span>

              <h2>
                {predictedPrice === null ? "—" : money(predictedPrice)}
              </h2>

              <p>
                {loading
                  ? "Your model is processing the property details..."
                  : predictedPrice !== null
                    ? "Prediction returned by the ML backend."
                    : "Submit the property details to get a prediction."}
              </p>

              <div className="result-divider" />

              <div className="result-foot">
                {loading ? (
                  <>
                    <LoaderCircle className="spin" size={15} />
                    Processing
                  </>
                ) : predictedPrice !== null ? (
                  <>
                    <CheckCircle2 size={15} />
                    Prediction successful
                  </>
                ) : (
                  <>
                    <span className="result-dot" />
                    Waiting for input
                  </>
                )}
              </div>

              {note && <p className="result-note">{note}</p>}

              {error && (
                <div className="error-message" role="alert">
                  <AlertCircle size={18} />
                  <span>{error}</span>
                </div>
              )}
            </div>

            <div className="panel summary-panel">
              <h3>Property summary</h3>
              <p className="summary-subtitle">Your current input values</p>

              <div className="summary-row">
                <span>Built-up area</span>
                <strong>{Number(form.area).toLocaleString("en-IN")} sq. ft.</strong>
              </div>
              <div className="summary-row">
                <span>Bedrooms</span>
                <strong>{form.bedrooms}</strong>
              </div>
              <div className="summary-row">
                <span>Location</span>
                <strong>{form.location || "—"}</strong>
              </div>
              <div className="summary-row">
                <span>Property type</span>
                <strong>
                  {Number(form.resale) === 1 ? "Resale" : "New property"}
                </strong>
              </div>
            </div>

            <div className="info-note">
              <Sparkles size={18} />
              <div>
                <strong>Machine learning prediction</strong>
                <p>
                  This is an educational estimate from your saved model,
                  not a verified market valuation.
                </p>
              </div>
            </div>
          </section>
        </div>

        <footer>EstateIQ · Educational project by G. Vishnu Vardhan</footer>
      </main>
    </div>
  );
}

export default App;